const POTRACE = "translate(0,1176) scale(0.1,-0.1)";

const SPOTS: { mode: CurioMode; label: string; cx: number }[] = [
  { mode: "snap", label: "SNAP", cx: 418 },
  { mode: "log", label: "LOG", cx: 637 },
  { mode: "share", label: "SHARE", cx: 858 },
];

const ICONS = { snap: SnapIcon, log: LogIcon, share: ShareIcon } as const;

// Content bounding box of the drawing, with a little breathing room.
const VX = 55;
const VY = 55;
const VW = 1200;
const VH = 1050;

const ICON_SIZE = 152;
const ICON_CY = 748;
const CAPTION_Y = 875;

export function CurioDoodle({ onPick }: { onPick: (mode: CurioMode) => void }) {
  return (
    <div className="relative mx-auto w-full select-none" style={{ aspectRatio: `${VW} / ${VH}` }}>
      <svg
        viewBox={`${VX} ${VY} ${VW} ${VH}`}
        className="absolute inset-0 h-full w-full"
        role="img"
        aria-label="Curio figure framing the snap, log and share tools"
      >
        <g transform={POTRACE} fill="var(--ink)" stroke="none">
          {STROKES.map((d, i) => (
            <path key={i} d={d} />
          ))}
        </g>

        {SPOTS.map(({ label, cx }) => (
          <text
            key={label}
            x={cx}
            y={CAPTION_Y}
            textAnchor="middle"
            fill="var(--ink)"
            style={{
              fontFamily: "var(--font-mono)",
              fontSize: 40,
              fontWeight: 500,
              letterSpacing: 1.5,
            }}
          >
            {label}
          </text>
        ))}
      </svg>

      {SPOTS.map(({ mode, label, cx }) => {
        const Icon = ICONS[mode];
        return (
          <button
            key={mode}
            type="button"
            onClick={() => onPick(mode)}
            aria-label={`See how ${label.toLowerCase()} works`}
            className="absolute flex items-center justify-center transition-transform duration-150 active:scale-95"
            style={{
              left: pct(cx - VX - ICON_SIZE * 0.9, VW),
              top: pct(ICON_CY - VY - ICON_SIZE * 0.85, VH),
              width: pct(ICON_SIZE * 1.8, VW),
              height: pct(ICON_SIZE * 1.7, VH),
              WebkitTapHighlightColor: "transparent",
              touchAction: "manipulation",
              background: "transparent",
            }}
          >
            <Icon size="56%" color="var(--ink)" />
          </button>
        );
      })}
    </div>
  );
}

function pct(value: number, total: number) {
  return `${(value / total) * 100}%`;
}
